import { enabledOrder } from "./generate.ts";
import type { Manifests } from "./graph.ts";
import { timelinePath } from "./timeline.ts";

export const FEATURES_INDEX = "FEATURES.md";

/** FEATURES.md: one line per feature, core first, each linking to its TIMELINE.md. */
export const featuresIndex = (manifests: Manifests): string => {
  const lines = enabledOrder(manifests).flatMap((name) => {
    const m = manifests.get(name);
    if (!m) return [];
    const kind = m.core ? "core" : "optional";
    const requires = m.requires.length ? [...m.requires].sort().join(", ") : "nothing";
    return [
      `- **${name}** (${kind}): ${m.description} Requires: ${requires}. [TIMELINE.md](${timelinePath(name)})`,
    ];
  });
  return [
    "<!-- Generated by `cf-saas-blocks sync` from each feature's feature.json. Do not edit. -->",
    "",
    "# Features",
    "",
    "Read this list, then the feature's TIMELINE.md, before you change a feature. With every change",
    "to a feature, add a line under Decisions or History in its TIMELINE.md.",
    "",
    ...lines,
    "",
  ].join("\n");
};
