import { byCodeUnit } from "@tanstack-cf-saas/lint";
import { enabledOrder } from "./generate.ts";
import { CORE_DIR, FEATURES_DIR, type Feature, type Features, isCoreModule } from "./manifest.ts";
import { timelinePath } from "./timeline.ts";

export const FEATURES_INDEX = "FEATURES.md";

const line = (m: Feature) => {
  const kind = m.required ? "required" : m.auto ? "auto" : "optional";
  const requires = m.requires.length ? [...m.requires].sort(byCodeUnit).join(", ") : "nothing";
  return `- **${m.name}** (${kind}): ${m.description} Requires: ${requires}. [TIMELINE.md](${timelinePath(m)})`;
};

/**
 * FEATURES.md: core modules, then features, one line each (required first), each linking to its
 * TIMELINE.md.
 */
export const featuresIndex = (manifests: Features): string => {
  const all = enabledOrder(manifests).flatMap((name) => manifests.get(name) ?? []);
  const core = all.filter(isCoreModule).map(line);
  const features = all.filter((m) => !isCoreModule(m)).map(line);
  return [
    "<!-- Generated by `cf-saas-blocks sync` from each feature's feature.json. Do not edit. -->",
    "",
    "# Features",
    "",
    "Read this list, then the feature's TIMELINE.md, before you change a feature. With every change",
    "to a feature, add a line under Decisions or History in its TIMELINE.md.",
    "",
    "## Core modules",
    "",
    `Shared modules in \`${CORE_DIR}/\`, each of one kind: components only, or services and helpers`,
    `only. Shared pure helpers sit in \`${CORE_DIR}/lib/\`.`,
    "",
    ...(core.length ? core : ["None."]),
    "",
    "## Features",
    "",
    `Everything with pages, or with components and logic of its own, in \`${FEATURES_DIR}/\`. Your`,
    "own features go here too.",
    "",
    ...(features.length ? features : ["None."]),
    "",
  ].join("\n");
};
